// 1666: the one Conventional Commit validator. Dependency-free on purpose (node builtins only), because the
// commit-msg hook (.githooks/commit-msg) and the land guard (land-guard.ts) both load it, and a hook that
// needs `bun install` to have worked is a hook that silently stops checking.
//
// Rule (charted in 251042d0): `<type>(<scope>): <subject>`, type one of TYPES, `!` before the colon for a
// breaking change. The scope is required: ticket work is `(PS-12)`, its per-project ref (1949; the older
// `(ob N)` still passes but warns, OB-1700), an architect chart `docs(chart)`.

import { readFileSync } from "node:fs";

export const TYPES = ["feat", "fix", "docs", "chore", "refactor", "test", "perf", "build", "ci", "style", "revert"] as const;

const SUBJECT = new RegExp(`^(${TYPES.join("|")})\\(([^()\\s][^()]*)\\)!?: \\S`);

// Subjects git or a rebase writes itself. Merge/Revert are generated by `git merge` / `git revert`;
// fixup!/squash!/amend! are autosquash markers that never survive to a landed commit.
const PASS_THROUGH = /^(Merge |Revert "|fixup! |squash! |amend! )/;

export interface SubjectCheck {
  ok: boolean;
  subject: string;
  /** Why it was refused; empty when ok. */
  reason: string;
  /** A passing subject that still deserves a second look (OB-1700); empty when none. Never refuses. */
  warning: string;
}

// OB-1700: `(ob 1697)` names the INTERNAL item id, while the ticket the owner and the builder see is `OB-1697`,
// a different item once the two sequences drifted apart (item 1697 is OB-1477; OB-1697 is item 2302). A
// builder that reads its ticket as `OB-1697` and scopes `(ob 1697)` writes a commit that claims another
// item's work, and `ob issue landed` then reports the wrong one as landed. It is a warning, not a refusal,
// because an item in a project with no key still shows its bare internal id and has no ref to write.
const OB_ID_SCOPE = /^[a-z]+\(([^()]*\bob\s+\d+[^()]*)\)!?:/i;

function scopeWarning(subject: string): string {
  const m = subject.match(OB_ID_SCOPE);
  if (!m) return "";
  return (
    `the scope \`(${m[1]})\` names an internal item id, not the ref shown on the ticket (OB-1700): ` +
    "item ids and OB-<n> numbers are different sequences that collide. Scope the commit by the ticket's ref, " +
    "`(OB-1697)` / `(PS-12)`, unless the item has no ref."
  );
}

export function checkSubject(subject: string): SubjectCheck {
  const s = subject.replace(/\r?\n.*$/s, "");
  if (PASS_THROUGH.test(s)) return { ok: true, subject: s, reason: "", warning: "" };
  if (SUBJECT.test(s)) return { ok: true, subject: s, reason: "", warning: scopeWarning(s) };
  const reason = !s.trim()
    ? "the subject is empty"
    : !/^[a-z]+(\(|!|:)/.test(s)
      ? "it does not start with `<type>(<scope>):`"
      : !(TYPES as readonly string[]).includes(s.match(/^[a-z]+/)![0])
        ? `\`${s.match(/^[a-z]+/)![0]}\` is not a Conventional Commit type`
        : "it needs a scope and a subject, as in `<type>(<scope>): <subject>`";
  return { ok: false, subject: s, reason, warning: "" };
}

/** The first line of a commit message file that is not a `#` comment (what git calls the subject). */
export function subjectOfMessage(message: string): string {
  return message.split("\n").find((l) => l.trim() !== "" && !l.startsWith("#")) ?? "";
}

function explain(c: SubjectCheck): string {
  return [
    `commit refused: "${c.subject}"`,
    `  ${c.reason}.`,
    `  Every commit is \`<type>(<scope>): <subject>\`, type one of ${TYPES.join(" ")} (add \`!\` for a breaking change).`,
    "  Ticket work is scoped by its ref, `(PS-12)` / `(OB-1697)` (the older `(ob N)` still passes but warns: it names an internal item id); an architect chart is `docs(chart): …`. Merge, Revert and fixup! subjects pass.",
  ].join("\n");
}

if (import.meta.main) {
  // Invoked by .githooks/commit-msg with the message file as $1.
  const file = process.argv[2];
  if (!file) {
    console.error("usage: conventional-commit.ts <commit-message-file>");
    process.exit(2);
  }
  const c = checkSubject(subjectOfMessage(readFileSync(file, "utf8")));
  if (!c.ok) {
    console.error(explain(c));
    process.exit(1);
  }
  if (c.warning) console.error(`commit-msg: warning: ${c.warning}`);
}
