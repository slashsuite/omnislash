#!/usr/bin/env bun
// Usage: bun src/export.ts [--check]   (bunx moon run state-machine:export [-- --check])
//
// Writes docs/role-state-machine.json and docs/role-state-machine.mmd from `roleMachine` (src/role.ts). With
// --check it writes nothing and exits 1, naming each file, when a committed copy differs from what the machine
// gives (OS-174). The JSON keeps the v1 schema slashslash's hand-kept file had (SS-130): version, roles, states,
// transitions with from, to, label, event, actor and source. OS-261 adds each state's `stage` (idea, plan, build, ship, done).
import { join } from "node:path";
import { ROLE_TRANSITIONS, ROLES, type RoleStateMeta, type RoleTransitionMeta, roleMachine, SKILLS_READ_AT } from "./role.ts";

/** The shapes OS-165 and slashslash read: one per JSON state and transition. */
export type ExportState = { id: string; label: string; role: string; stage: string; human_required: boolean; terminal: boolean };
export type ExportTransition = { from: string; to: string; label: string; event: string; actor: string; source: string };

/** Every state of the machine, in definition order, with its meta. */
export function exportStates(): ExportState[] {
  return Object.entries(roleMachine.states).map(([id, node]) => {
    const meta = node.meta as RoleStateMeta;
    return { id, label: meta.label, role: meta.role, stage: meta.stage, human_required: meta.human_required, terminal: node.type === "final" };
  });
}

/** Every move of the machine, read off its state nodes, in the order role.ts lists them. */
export function exportTransitions(): ExportTransition[] {
  const order = new Map(ROLE_TRANSITIONS.map((t, i) => [`${t.from}\0${t.event}`, i]));
  const out: ExportTransition[] = [];
  for (const [from, node] of Object.entries(roleMachine.states)) {
    for (const [event, edges] of node.transitions) {
      for (const edge of edges) {
        const meta = edge.meta as RoleTransitionMeta;
        const to = edge.target?.[0]?.key;
        if (to === undefined) throw new Error(`role machine: '${event}' from '${from}' has no target`);
        out.push({ from, to, label: meta.label, event, actor: meta.actor, source: meta.source });
      }
    }
  }
  const rank = (t: ExportTransition) => order.get(`${t.from}\0${t.event}`) ?? Number.MAX_SAFE_INTEGER;
  return out.toSorted((a, b) => rank(a) - rank(b));
}

/** `{ "k": v, ... }` on one line, as the hand-kept file wrote each state and transition. */
const inline = (o: object) =>
  `{ ${Object.entries(o)
    .map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`)
    .join(", ")} }`;

function renderJson(): string {
  const states = exportStates();
  const transitions = exportTransitions();
  const lines = [
    "{",
    `  "version": 1,`,
    `  "generated_by": "bunx moon run state-machine:export, from platform/state-machine/src/role.ts in omnislash",`,
    `  "read_at": {`,
    `    "omnibus_skills": ${JSON.stringify(SKILLS_READ_AT)}`,
    "  },",
    `  "source_prefixes": {`,
    `    "skills/": "omnibus repo, skills/<name>/SKILL.md:<line>",`,
    `    "platform/": "omnislash repo, <path>#<event or function> that applies the move",`,
    `    "apps/cli/": "omnislash repo, <path>#<function> that applies the move"`,
    "  },",
    `  "roles": [`,
    ROLES.map((r) => `    ${JSON.stringify(r)}`).join(",\n"),
    "  ],",
    `  "states": [`,
    states.map((s) => `    ${inline(s)}`).join(",\n"),
    "  ],",
    `  "transitions": [`,
    transitions.map((t) => `    ${inline(t)}`).join(",\n"),
    "  ]",
    "}",
  ];
  return `${lines.join("\n")}\n`;
}

function renderMermaid(): string {
  const states = exportStates();
  const transitions = exportTransitions();
  const lines = [
    "%% Generated by `bunx moon run state-machine:export` from platform/state-machine/src/role.ts in omnislash. Do not edit by hand.",
    "%% Mirrors docs/role-state-machine.json: one state per JSON state and one arrow per JSON transition, in JSON order.",
    "%% Human states carry class human. Terminal states lead to [*].",
    "stateDiagram-v2",
    ...states.map((s) => `    state "${s.label} (${s.role})" as ${s.id}`),
    `    [*] --> ${roleMachine.config.initial as string}`,
    ...transitions.map((t) => `    ${t.from} --> ${t.to}: ${t.label}`),
    ...states.filter((s) => s.terminal).map((s) => `    ${s.id} --> [*]`),
    "    classDef human fill:#ffe08a,stroke:#b8860b,stroke-width:3px,color:#000",
    "    classDef terminal fill:#d9d9d9,stroke:#555,color:#000",
    `    class ${states.filter((s) => s.human_required).map((s) => s.id).join(",")} human`,
    `    class ${states.filter((s) => s.terminal).map((s) => s.id).join(",")} terminal`,
  ];
  return `${lines.join("\n")}\n`;
}

/** The generated files, keyed by their path from the workspace root. */
export function renderAll(): Record<string, string> {
  return { "docs/role-state-machine.json": renderJson(), "docs/role-state-machine.mmd": renderMermaid() };
}

if (import.meta.main) {
  const root = join(import.meta.dir, "../../..");
  const args = Bun.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    console.error("usage: bun src/export.ts [--check]");
    process.exit(2);
  }
  const check = args[0] === "--check";
  const drifted: string[] = [];
  for (const [path, text] of Object.entries(renderAll())) {
    const file = Bun.file(join(root, path));
    const current = (await file.exists()) ? await file.text() : null;
    if (current === text) continue;
    if (check) drifted.push(path);
    else {
      await Bun.write(file, text);
      console.log(`wrote ${path}`);
    }
  }
  if (drifted.length) {
    for (const path of drifted) console.error(`FAIL ${path} is not what platform/state-machine/src/role.ts gives`);
    console.error("run: bunx moon run state-machine:export, and commit the result");
    process.exit(1);
  }
  if (check) console.log("ok: docs/role-state-machine.json and .mmd match the role machine");
}
