// --- ob 323 (Postgres migration, phase 3): the SQLite -> Postgres data move ---
//
// A one-shot exporter, built to be run for real against the 62 MB live tracker inside the ob 326 window.
// Everything below is shaped by three constraints, and each one is the reason for code that would
// otherwise look over-careful.
//
// 1. VERIFICATION IS THE DELIVERABLE, NOT THE EXIT CODE. The family-archive work was told "success" twice
//    by tools that had lost data -- an rsync and a ZFS replication, one of them 32 files short. So this
//    exporter re-reads BOTH sides after the load and reports rows(src) rows(dst) hash(src) hash(dst) per
//    table. The hash is over the values themselves, not over a byte stream neither side ever produced, so
//    a right-count wrong-content load still fails. An `ob pg-export` that exits 0 having copied nothing
//    is a shape this cannot have: zero tables verified is a failure.
//
// 2. THE SEQUENCE OBLIGATION ob 321 HANDED US. Identity columns are GENERATED BY DEFAULT rather than
//    ALWAYS precisely so the EXISTING ids can be inserted and every foreign key stays intact. The cost is
//    that each sequence must then be re-set, or the first live insert after the cutover collides with a
//    row that is already there. resetSequences() below is that half of the bargain, and the report prints
//    the max id and the next value beside each other so the reset is EVIDENCE rather than a claim.
//
// 3. THE COLUMN LIST IS DISCOVERED, NEVER HARD-CODED. ob 322 adds tsvector columns to the same target
//    schema while this is being built. A hard-coded column list would be wrong the day 322 lands, so the
//    source shape comes from sqlite_master/PRAGMA and the target shape from information_schema, and the
//    copied set is the intersection. A target-only column (322's search_vec, maintained by Postgres) is
//    reported and left to its default; it is not copied and not hashed.
//
// SAFETY. There is NO default source and NO default target: both are named explicitly on the command line
// or the command refuses. The exporter only ever READS the SQLite side (opened readonly), and the whole
// load is one transaction, so a failure leaves the target exactly as it was rather than half-loaded.

import { Database } from "bun:sqlite";
import { createHash } from "node:crypto";

// --- the Postgres seam ------------------------------------------------------------------------------
//
// Injected rather than imported so every test in this repo runs with NO Postgres and NO network. The live
// implementation (Bun's built-in SQL client) lives in the command module; everything here talks to this.

export interface PgClient {
	query(sql: string, params?: unknown[]): Promise<Record<string, unknown>[]>;
}

// --- shapes -----------------------------------------------------------------------------------------

export interface SourceColumn {
	name: string;
	/** the DECLARED type; SQLite does not enforce it, which is what makes the scan below necessary. */
	declared: string;
}

export interface SourceTable {
	name: string;
	columns: SourceColumn[];
	hasRowid: boolean;
}

export interface TargetColumn {
	name: string;
	/** information_schema.columns.data_type, e.g. "integer" / "text" / "USER-DEFINED" (tsvector). */
	dataType: string;
	/** the identity/serial sequence behind this column, or null. Non-null is what obliges the setval. */
	sequence: string | null;
}

export interface TargetTable {
	name: string;
	columns: TargetColumn[];
}

/** A copied column, with the target type that decides how a loosely-typed SQLite value is coerced. */
export interface CopiedColumn {
	name: string;
	kind: "integer" | "text";
}

export interface TablePlan {
	table: string;
	columns: CopiedColumn[];
	/** present in the target and not in the source: 322's search_vec. Left to its default. */
	targetOnlyColumns: string[];
	/** present in the source and not in the target: data that WOULD be dropped. */
	sourceOnlyColumns: string[];
	sequences: { column: string; sequence: string }[];
	hasRowid: boolean;
}

export interface ExportPlan {
	/** load order: every table appears after every table it references. */
	tables: TablePlan[];
	/** source tables with no target table, split by whether the seam explains them. */
	expectedSkips: string[];
	unexpectedSkips: string[];
	/** target tables with no source table. Loaded with nothing; reported so an empty one is not a surprise. */
	targetOnlyTables: string[];
	problems: string[];
}

export interface ColumnCoercion {
	table: string;
	column: string;
	/** the SQLite storage type found where the target wanted something else. */
	from: string;
	count: number;
	samples: string[];
}

export interface TableResult {
	table: string;
	sourceRows: number;
	sourceHash: string;
	targetRows: number | null;
	targetHash: string | null;
	ok: boolean | null;
}

export interface SequenceResult {
	table: string;
	column: string;
	sequence: string;
	maxId: number | null;
	/** the value the NEXT insert will be handed. Must be greater than maxId or the cutover collides. */
	nextValue: number;
	ok: boolean;
}

export interface ExportReport {
	mode: "dry-run" | "load" | "verify-only";
	source: string;
	startedAt: string;
	finishedAt: string;
	tables: TableResult[];
	sequences: SequenceResult[];
	coercions: ColumnCoercion[];
	expectedSkips: string[];
	unexpectedSkips: string[];
	targetOnlyTables: string[];
	targetOnlyColumns: { table: string; columns: string[] }[];
	truncated: boolean;
	ok: boolean;
	failures: string[];
}

// --- reading the two shapes -------------------------------------------------------------------------

/**
 * The tables SQLite does not own itself. `__drizzle_migrations` is the SQLite chain's bookkeeping and is
 * deliberately not carried across: the Postgres chain restarts at 0000 with its own (map, phase 1).
 * The fts5 virtual tables and their 25 shadow tables have no Postgres analogue at all -- search is a
 * tsvector column on the source table, so there is nothing for them to be copied INTO (ob 322).
 */
const FTS_BASES = ["item", "pr_comment", "email", "slack", "whatsapp"];
const FTS_SUFFIXES = ["", "_data", "_idx", "_content", "_docsize", "_config"];

export function expectedSkip(table: string): boolean {
	if (table.startsWith("sqlite_")) return true;
	if (table === "__drizzle_migrations") return true;
	for (const base of FTS_BASES) {
		for (const suffix of FTS_SUFFIXES) if (table === `${base}_fts${suffix}`) return true;
	}
	return false;
}

export function describeSource(db: Database): SourceTable[] {
	const rows = db
		.query<{ name: string; sql: string | null }, []>(
			"SELECT name, sql FROM sqlite_master WHERE type = 'table' ORDER BY name",
		)
		.all();
	const tables: SourceTable[] = [];
	for (const row of rows) {
		const info = db
			.query<{ name: string; type: string }, []>(`PRAGMA table_info("${row.name.replaceAll('"', '""')}")`)
			.all();
		tables.push({
			name: row.name,
			columns: info.map((c) => ({ name: c.name, declared: c.type })),
			// WITHOUT ROWID costs us only the row locator in an error message, so it is detected rather
			// than assumed either way.
			hasRowid: !/without\s+rowid/i.test(row.sql ?? ""),
		});
	}
	return tables;
}

export async function describeTarget(pg: PgClient): Promise<TargetTable[]> {
	const rows = await pg.query(
		`SELECT c.table_name AS t, c.column_name AS c, c.data_type AS d,
		        pg_get_serial_sequence(format('%I.%I', c.table_schema, c.table_name), c.column_name) AS seq
		 FROM information_schema.columns c
		 JOIN information_schema.tables tb
		   ON tb.table_schema = c.table_schema AND tb.table_name = c.table_name
		 WHERE c.table_schema = 'public' AND tb.table_type = 'BASE TABLE'
		 ORDER BY c.table_name, c.ordinal_position`,
	);
	const byTable = new Map<string, TargetTable>();
	for (const row of rows) {
		const name = String(row.t);
		let table = byTable.get(name);
		if (!table) {
			table = { name, columns: [] };
			byTable.set(name, table);
		}
		table.columns.push({
			name: String(row.c),
			dataType: String(row.d),
			sequence: row.seq === null || row.seq === undefined ? null : String(row.seq),
		});
	}
	return [...byTable.values()];
}

/** child -> parent edges, read from the TARGET so 322's additions are covered without editing this file. */
export async function targetForeignKeys(pg: PgClient): Promise<{ child: string; parent: string }[]> {
	const rows = await pg.query(
		`SELECT ch.relname AS child, pa.relname AS parent
		 FROM pg_constraint c
		 JOIN pg_class ch ON ch.oid = c.conrelid
		 JOIN pg_class pa ON pa.oid = c.confrelid
		 JOIN pg_namespace n ON n.oid = ch.relnamespace
		 WHERE c.contype = 'f' AND n.nspname = 'public'`,
	);
	return rows.map((r) => ({ child: String(r.child), parent: String(r.parent) }));
}

// --- load order -------------------------------------------------------------------------------------

/**
 * Kahn's algorithm over the foreign keys, so a table is loaded only once everything it references is in.
 * A SELF-reference is not an ordering problem between tables and is ignored here (row order within the
 * table would be the fix, and the schema has none today).
 *
 * A CYCLE is refused by name rather than worked around. The escape hatches all cost more than they are
 * worth here: the constraints are not DEFERRABLE, and `session_replication_role = replica` needs a
 * superuser the ob role deliberately is not (ob 320). Refusing names the cycle, which is the thing a human
 * would need to know anyway.
 */
export function loadOrder(
	tables: string[],
	edges: { child: string; parent: string }[],
): { order: string[]; cycle: string[] } {
	const present = new Set(tables);
	const parents = new Map<string, Set<string>>();
	const children = new Map<string, Set<string>>();
	for (const t of tables) {
		parents.set(t, new Set());
		children.set(t, new Set());
	}
	for (const { child, parent } of edges) {
		if (child === parent) continue;
		if (!present.has(child) || !present.has(parent)) continue;
		parents.get(child)!.add(parent);
		children.get(parent)!.add(child);
	}
	// Sorted so the order is deterministic run to run, which makes two reports diffable.
	const ready = tables.filter((t) => parents.get(t)!.size === 0).sort();
	const order: string[] = [];
	while (ready.length > 0) {
		const next = ready.shift()!;
		order.push(next);
		const freed: string[] = [];
		for (const child of children.get(next)!) {
			const remaining = parents.get(child)!;
			remaining.delete(next);
			if (remaining.size === 0) freed.push(child);
		}
		freed.sort();
		for (const f of freed) ready.push(f);
		ready.sort();
	}
	if (order.length === tables.length) return { order, cycle: [] };
	return { order, cycle: tables.filter((t) => !order.includes(t)).sort() };
}

// --- planning ---------------------------------------------------------------------------------------

/** The target types this exporter can produce from a SQLite value. ob 327's retype will widen this. */
function columnKind(dataType: string): "integer" | "text" | null {
	if (dataType === "integer") return "integer";
	if (dataType === "text") return "text";
	return null;
}

export function buildPlan(input: {
	source: SourceTable[];
	target: TargetTable[];
	edges: { child: string; parent: string }[];
}): ExportPlan {
	const sourceByName = new Map(input.source.map((t) => [t.name, t]));
	const targetByName = new Map(input.target.map((t) => [t.name, t]));
	const problems: string[] = [];
	const expectedSkips: string[] = [];
	const unexpectedSkips: string[] = [];

	for (const t of input.source) {
		if (targetByName.has(t.name)) continue;
		if (expectedSkip(t.name)) expectedSkips.push(t.name);
		else unexpectedSkips.push(t.name);
	}
	const targetOnlyTables = input.target.filter((t) => !sourceByName.has(t.name)).map((t) => t.name);

	const plans = new Map<string, TablePlan>();
	for (const target of input.target) {
		const source = sourceByName.get(target.name);
		if (!source) continue;
		const sourceColumns = new Set(source.columns.map((c) => c.name));
		const targetColumns = new Set(target.columns.map((c) => c.name));
		const columns: CopiedColumn[] = [];
		for (const column of target.columns) {
			if (!sourceColumns.has(column.name)) continue;
			const kind = columnKind(column.dataType);
			if (kind === null) {
				// Both sides have the column and this exporter cannot produce the target type. Naming it is
				// the honest answer; guessing a conversion is how a migration corrupts a column quietly.
				problems.push(
					`${target.name}.${column.name}: target type '${column.dataType}' is neither integer nor text, so this exporter cannot convert the SQLite value for it`,
				);
				continue;
			}
			columns.push({ name: column.name, kind });
		}
		plans.set(target.name, {
			table: target.name,
			columns,
			targetOnlyColumns: target.columns.filter((c) => !sourceColumns.has(c.name)).map((c) => c.name),
			sourceOnlyColumns: source.columns.filter((c) => !targetColumns.has(c.name)).map((c) => c.name),
			sequences: target.columns
				.filter((c) => c.sequence !== null)
				.map((c) => ({ column: c.name, sequence: c.sequence! })),
			hasRowid: source.hasRowid,
		});
	}

	const { order, cycle } = loadOrder([...plans.keys()], input.edges);
	if (cycle.length > 0) {
		problems.push(
			`foreign keys form a cycle across ${cycle.join(", ")}, so there is no order in which these tables can be loaded. The constraints are not DEFERRABLE and the ob role is not a superuser, so this needs a schema decision, not a flag.`,
		);
	}
	return {
		tables: order.map((name) => plans.get(name)!),
		expectedSkips,
		unexpectedSkips,
		targetOnlyTables,
		problems,
	};
}

// --- hashing ----------------------------------------------------------------------------------------
//
// ORDER-INDEPENDENT ON PURPOSE. One table (whatsapp_message) has no primary key at all, and Postgres has
// no obligation to return rows in insertion order anyway, so a hash that depended on row order would fail
// for reasons that are not data loss. Each row is digested on its own and the digests are SUMMED as
// 256-bit integers. Summing rather than XOR because XOR cancels duplicate rows in pairs, and "two
// identical rows became zero rows" is exactly the class of loss this exists to catch.

/**
 * The canonical bytes of one row. Columns are taken in sorted order so neither side's declaration order
 * can affect the result, and each value carries a type tag and (for text) a length, so `null`, the empty
 * string, the string "5" and the integer 5 can never digest the same.
 */
export function canonicalRow(columns: string[], values: Map<string, string | number | null>): string {
	const parts: string[] = [];
	for (const name of [...columns].sort()) {
		const value = values.get(name) ?? null;
		if (value === null) parts.push(`${name}=N`);
		else if (typeof value === "number") parts.push(`${name}=I${value}`);
		else parts.push(`${name}=S${Buffer.byteLength(value, "utf8")}:${value}`);
	}
	return parts.join("");
}

export class RowHash {
	private readonly acc = new Uint8Array(32);
	private rows = 0;

	add(canonical: string): void {
		const digest = createHash("sha256").update(canonical, "utf8").digest();
		let carry = 0;
		for (let i = 31; i >= 0; i--) {
			const sum = this.acc[i]! + digest[i]! + carry;
			this.acc[i] = sum & 0xff;
			carry = sum >> 8;
		}
		this.rows++;
	}

	get count(): number {
		return this.rows;
	}

	hex(): string {
		return Buffer.from(this.acc).toString("hex");
	}
}

// --- reading the source, with SQLite's loose typing handled explicitly -------------------------------

function quoteIdent(name: string): string {
	return `"${name.replaceAll('"', '""')}"`;
}

/**
 * SQLite does not enforce declared types, so a column declared TEXT can hold an integer and a column
 * declared INTEGER can hold a string. Every value is therefore read WITH its storage type
 * (`typeof(col)`), and text-target columns are read a second time through SQLite's OWN text rendering
 * (`CAST(col AS TEXT)`) rather than JavaScript's -- `String(3.0)` is "3" where SQLite writes "3.0", and
 * that one character difference would be a silent content change on a text column.
 *
 * The blob guard is on the CAST rather than around it because the cast is evaluated for every row whether
 * or not we go on to use it, and a blob cast to text is not a string this process should be materialising.
 */
export function sourceSelect(plan: TablePlan): string {
	const parts: string[] = [];
	if (plan.hasRowid) parts.push("rowid AS __rowid");
	plan.columns.forEach((column, i) => {
		const ident = quoteIdent(column.name);
		parts.push(`typeof(${ident}) AS __t${i}`);
		parts.push(`${ident} AS __v${i}`);
		if (column.kind === "text") {
			parts.push(`CASE WHEN typeof(${ident}) = 'blob' THEN NULL ELSE CAST(${ident} AS TEXT) END AS __s${i}`);
		}
	});
	return `SELECT ${parts.join(", ")} FROM ${quoteIdent(plan.table)}`;
}

export interface CoercionSink {
	record(table: string, column: string, from: string, sample: string): void;
}

export class Coercions implements CoercionSink {
	private readonly byKey = new Map<string, ColumnCoercion>();

	record(table: string, column: string, from: string, sample: string): void {
		const key = [table, column, from].join(String.fromCharCode(31));
		let entry = this.byKey.get(key);
		if (!entry) {
			entry = { table, column, from, count: 0, samples: [] };
			this.byKey.set(key, entry);
		}
		entry.count++;
		if (entry.samples.length < 5) entry.samples.push(sample.length > 60 ? `${sample.slice(0, 60)}...` : sample);
	}

	all(): ColumnCoercion[] {
		return [...this.byKey.values()].sort((a, b) => a.table.localeCompare(b.table) || a.column.localeCompare(b.column));
	}
}

/** Postgres int4. A wider value has to be refused: silently truncating a *_cents column is money lost. */
/** Written this way on purpose: a literal NUL byte in a source file is not something to leave lying around. */
const NUL = String.fromCharCode(0);

const INT4_MIN = -2147483648;
const INT4_MAX = 2147483647;

export class CellError extends Error {}

function locate(plan: TablePlan, row: Record<string, unknown>, column: string): string {
	const rowid = plan.hasRowid ? ` rowid ${String(row.__rowid)}` : "";
	return `${plan.table}.${column}${rowid}`;
}

/**
 * One SQLite row -> the values that will be inserted, in the copied-column order. Every judgement call is
 * either a REFUSAL naming the cell, or a coercion that is COUNTED and sampled in the report. Nothing is
 * changed silently, which is the whole point: a cutover that quietly rewrote 40 values is one nobody can
 * audit afterwards.
 */
export function coerceRow(
	plan: TablePlan,
	row: Record<string, unknown>,
	coercions: CoercionSink,
): (string | number | null)[] {
	return plan.columns.map((column, i) => {
		const storage = String(row[`__t${i}`]);
		const raw = row[`__v${i}`];
		if (storage === "null" || raw === null || raw === undefined) return null;

		if (column.kind === "integer") {
			if (storage === "integer") {
				const n = typeof raw === "bigint" ? Number(raw) : Number(raw);
				if (!Number.isSafeInteger(n) || n < INT4_MIN || n > INT4_MAX) {
					throw new CellError(
						`${locate(plan, row, column.name)}: ${String(raw)} does not fit a Postgres integer (int4 is ${INT4_MIN}..${INT4_MAX}). Widening the column is ob 327's retype, not this exporter's call.`,
					);
				}
				return n;
			}
			if (storage === "real") {
				const n = Number(raw);
				if (!Number.isInteger(n)) {
					throw new CellError(
						`${locate(plan, row, column.name)}: the target column is integer and SQLite stored the real ${String(raw)}, which has no lossless integer form.`,
					);
				}
				if (n < INT4_MIN || n > INT4_MAX) {
					throw new CellError(`${locate(plan, row, column.name)}: ${String(raw)} does not fit a Postgres integer.`);
				}
				coercions.record(plan.table, column.name, "real", String(raw));
				return n;
			}
			if (storage === "text") {
				const text = String(raw);
				if (!/^-?\d+$/.test(text)) {
					throw new CellError(
						`${locate(plan, row, column.name)}: the target column is integer and SQLite stored the text ${JSON.stringify(text)}, which is not an integer.`,
					);
				}
				const n = Number(text);
				if (!Number.isSafeInteger(n) || n < INT4_MIN || n > INT4_MAX) {
					throw new CellError(`${locate(plan, row, column.name)}: ${text} does not fit a Postgres integer.`);
				}
				coercions.record(plan.table, column.name, "text", text);
				return n;
			}
			throw new CellError(
				`${locate(plan, row, column.name)}: the target column is integer and SQLite stored a ${storage}, which this exporter will not guess at.`,
			);
		}

		// text target
		if (storage === "blob") {
			throw new CellError(
				`${locate(plan, row, column.name)}: the target column is text and SQLite stored a blob. Postgres text is not a byte string, so there is no round-trip; this needs a bytea column (ob 327) or the row removed.`,
			);
		}
		const rendered = row[`__s${i}`];
		if (rendered === null || rendered === undefined) {
			throw new CellError(`${locate(plan, row, column.name)}: SQLite could not render the value as text.`);
		}
		const text = String(rendered);
		if (text.includes(NUL)) {
			// Postgres rejects this itself, but its own message names neither the table nor the row, and at
			// 03:00 in a cutover window that difference is the whole debugging session.
			throw new CellError(
				`${locate(plan, row, column.name)}: the value contains a NUL byte, which Postgres text cannot store. SQLite can, so this row has to be fixed at the source before the export.`,
			);
		}
		if (storage !== "text") coercions.record(plan.table, column.name, storage, text);
		return text;
	});
}

// --- the load ---------------------------------------------------------------------------------------

/** Postgres caps a statement at 65535 bind parameters; the batch is sized under that and then capped. */
export function batchSize(columnCount: number): number {
	if (columnCount <= 0) return 1;
	return Math.max(1, Math.min(1000, Math.floor(60000 / columnCount)));
}

function insertStatement(plan: TablePlan, rows: number): string {
	const columns = plan.columns.map((c) => quoteIdent(c.name)).join(", ");
	const tuples: string[] = [];
	let param = 1;
	for (let r = 0; r < rows; r++) {
		const placeholders = plan.columns.map(() => `$${param++}`);
		tuples.push(`(${placeholders.join(", ")})`);
	}
	return `INSERT INTO ${quoteIdent(plan.table)} (${columns}) VALUES ${tuples.join(", ")}`;
}

/**
 * Reads one source table, hashing every row as it goes, and (unless this is a dry run or a verify) writes
 * it to the target. The hash is computed from the values ACTUALLY SENT, so the source side of the report
 * describes what was transmitted rather than a separate re-reading that could disagree with it.
 */
export async function loadTable(input: {
	db: Database;
	pg: PgClient;
	plan: TablePlan;
	coercions: CoercionSink;
	write: boolean;
}): Promise<{ rows: number; hash: string }> {
	const { db, pg, plan, coercions, write } = input;
	const names = plan.columns.map((c) => c.name);
	const hash = new RowHash();
	const size = batchSize(plan.columns.length);
	let batch: (string | number | null)[] = [];
	let batched = 0;

	const flush = async (): Promise<void> => {
		if (batched === 0) return;
		if (write) await pg.query(insertStatement(plan, batched), batch);
		batch = [];
		batched = 0;
	};

	for (const row of db.query(sourceSelect(plan)).iterate() as Iterable<Record<string, unknown>>) {
		const values = coerceRow(plan, row, coercions);
		const map = new Map<string, string | number | null>();
		names.forEach((name, i) => map.set(name, values[i]!));
		hash.add(canonicalRow(names, map));
		if (plan.columns.length === 0) continue;
		batch.push(...values);
		batched++;
		if (batched >= size) await flush();
	}
	await flush();
	return { rows: hash.count, hash: hash.hex() };
}

/**
 * Re-reads a target table and hashes it the same way. A CURSOR rather than LIMIT/OFFSET because one table
 * has no primary key to paginate stably by, and rather than a whole-table fetch because "it is only 62 MB
 * today" is not a property of the tool.
 */
export async function hashTarget(pg: PgClient, plan: TablePlan): Promise<{ rows: number; hash: string }> {
	const names = plan.columns.map((c) => c.name);
	const hash = new RowHash();
	if (names.length === 0) {
		const counted = await pg.query(`SELECT count(*)::int AS n FROM ${quoteIdent(plan.table)}`);
		return { rows: Number(counted[0]?.n ?? 0), hash: hash.hex() };
	}
	const columns = names.map(quoteIdent).join(", ");
	const cursor = "ob323_verify";
	await pg.query("BEGIN READ ONLY");
	try {
		await pg.query(`DECLARE ${cursor} NO SCROLL CURSOR FOR SELECT ${columns} FROM ${quoteIdent(plan.table)}`);
		for (;;) {
			const rows = await pg.query(`FETCH 2000 FROM ${cursor}`);
			if (rows.length === 0) break;
			for (const row of rows) {
				const map = new Map<string, string | number | null>();
				for (const name of names) {
					const value = row[name];
					if (value === null || value === undefined) map.set(name, null);
					else if (typeof value === "number") map.set(name, value);
					else if (typeof value === "bigint") map.set(name, Number(value));
					else map.set(name, String(value));
				}
				hash.add(canonicalRow(names, map));
			}
		}
		await pg.query(`CLOSE ${cursor}`);
		await pg.query("COMMIT");
	} catch (err) {
		await pg.query("ROLLBACK").catch(() => {});
		throw err;
	}
	return { rows: hash.count, hash: hash.hex() };
}

/**
 * THE ob 321 OBLIGATION. Identity is GENERATED BY DEFAULT so the existing ids could be inserted; without
 * this, the sequence is still sitting at 1 and the first `ob add` after the cutover collides with a row
 * from 2024. `setval(seq, max+1, false)` leaves the sequence about to hand out max+1: `false` means "not
 * yet called", so nextval returns the value as given rather than one past it. An empty table lands on 1,
 * which is where a fresh sequence starts anyway.
 */
export async function resetSequences(pg: PgClient, plan: TablePlan): Promise<SequenceResult[]> {
	const results: SequenceResult[] = [];
	for (const { column, sequence } of plan.sequences) {
		const rows = await pg.query(
			`SELECT max(${quoteIdent(column)})::bigint AS max_id FROM ${quoteIdent(plan.table)}`,
		);
		const maxRaw = rows[0]?.max_id;
		const maxId = maxRaw === null || maxRaw === undefined ? null : Number(maxRaw);
		await pg.query(`SELECT setval($1, $2, false)`, [sequence, (maxId ?? 0) + 1]);
		results.push({ table: plan.table, column, sequence, maxId, nextValue: (maxId ?? 0) + 1, ok: false });
	}
	return results;
}

/**
 * Reads back what the sequence will ACTUALLY hand out, without consuming a value the way nextval would.
 * `is_called` is the difference between "last_value has been used" and "last_value is next up", and
 * getting it backwards is how a verification passes while the sequence is still one short.
 */
export async function readSequences(pg: PgClient, results: SequenceResult[]): Promise<SequenceResult[]> {
	const out: SequenceResult[] = [];
	for (const result of results) {
		const rows = await pg.query(`SELECT last_value, is_called FROM ${result.sequence}`);
		const lastValue = Number(rows[0]?.last_value ?? 0);
		const isCalled = rows[0]?.is_called === true || rows[0]?.is_called === "t";
		const nextValue = isCalled ? lastValue + 1 : lastValue;
		out.push({ ...result, nextValue, ok: nextValue > (result.maxId ?? 0) });
	}
	return out;
}

// --- the run ----------------------------------------------------------------------------------------

export interface ExportOptions {
	sourcePath: string;
	dryRun: boolean;
	verifyOnly: boolean;
	truncate: boolean;
	allowMissingTargetTables: boolean;
	allowMissingTargetColumns: boolean;
	now?: () => Date;
}

export class ExportRefusal extends Error {}

/** Which target tables already hold rows. Cheap: one LIMIT 1 per table, not 65 counts. */
export async function nonEmptyTargets(pg: PgClient, tables: string[]): Promise<string[]> {
	const nonEmpty: string[] = [];
	for (const table of tables) {
		const rows = await pg.query(`SELECT 1 AS x FROM ${quoteIdent(table)} LIMIT 1`);
		if (rows.length > 0) nonEmpty.push(table);
	}
	return nonEmpty;
}

export async function runExport(input: {
	db: Database;
	pg: PgClient;
	options: ExportOptions;
}): Promise<ExportReport> {
	const { db, pg, options } = input;
	const now = options.now ?? (() => new Date());
	const startedAt = now().toISOString();

	const source = describeSource(db);
	const target = await describeTarget(pg);
	if (target.length === 0) {
		throw new ExportRefusal(
			"the target database has no tables in schema 'public'. Apply the ob 321 baseline first; this exporter moves data and never creates schema.",
		);
	}
	const edges = await targetForeignKeys(pg);
	const plan = buildPlan({ source, target, edges });

	const refusals = [...plan.problems];
	if (plan.unexpectedSkips.length > 0 && !options.allowMissingTargetTables) {
		refusals.push(
			`these source tables have no table in the target and are not part of the known fts/bookkeeping seam: ${plan.unexpectedSkips.join(", ")}. Their rows would simply not be moved. Pass --allow-missing-target-tables to accept that deliberately.`,
		);
	}
	const dropped = plan.tables.filter((t) => t.sourceOnlyColumns.length > 0);
	if (dropped.length > 0 && !options.allowMissingTargetColumns) {
		refusals.push(
			`these source columns have no column in the target, so their values would be dropped: ${dropped
				.map((t) => t.sourceOnlyColumns.map((c) => `${t.table}.${c}`).join(", "))
				.join(", ")}. Pass --allow-missing-target-columns to accept that deliberately.`,
		);
	}
	if (refusals.length > 0) throw new ExportRefusal(refusals.join("\n"));

	// IDEMPOTENCY. Refusing is the default because the alternative -- a second run appending to a target
	// that already has the data -- is the outcome nobody can see until much later. --truncate is the
	// deliberate opposite, and it is a single statement so the target is never half-cleared.
	let truncated = false;
	const targetTables = plan.tables.map((t) => t.table);
	if (!options.dryRun && !options.verifyOnly) {
		const nonEmpty = await nonEmptyTargets(pg, targetTables);
		if (nonEmpty.length > 0) {
			if (!options.truncate) {
				throw new ExportRefusal(
					`the target already holds rows in ${nonEmpty.length} table(s): ${nonEmpty.slice(0, 8).join(", ")}${
						nonEmpty.length > 8 ? ", ..." : ""
					}. This exporter will not add to a target it did not empty, because a doubled row set looks like a successful run. Re-run with --truncate to empty every target table first, deliberately.`,
				);
			}
		}
	}

	const coercions = new Coercions();
	const results: TableResult[] = [];
	let sequences: SequenceResult[] = [];

	if (options.verifyOnly) {
		for (const table of plan.tables) {
			const src = await loadTable({ db, pg, plan: table, coercions, write: false });
			const dst = await hashTarget(pg, table);
			results.push({
				table: table.table,
				sourceRows: src.rows,
				sourceHash: src.hash,
				targetRows: dst.rows,
				targetHash: dst.hash,
				ok: src.rows === dst.rows && src.hash === dst.hash,
			});
		}
		const declared: SequenceResult[] = plan.tables.flatMap((t) =>
			t.sequences.map((s) => ({ table: t.table, column: s.column, sequence: s.sequence, maxId: null, nextValue: 0, ok: false })),
		);
		for (const entry of declared) {
			const rows = await pg.query(`SELECT max(${quoteIdent(entry.column)})::bigint AS max_id FROM ${quoteIdent(entry.table)}`);
			const maxRaw = rows[0]?.max_id;
			entry.maxId = maxRaw === null || maxRaw === undefined ? null : Number(maxRaw);
		}
		sequences = await readSequences(pg, declared);
	} else if (options.dryRun) {
		// A dry run is a FULL source scan, not a plan printout: it reads and coerces every row, so the
		// type problems that would stop the real run at 03:00 are found now, at no risk. It writes nothing.
		for (const table of plan.tables) {
			const src = await loadTable({ db, pg, plan: table, coercions, write: false });
			results.push({
				table: table.table,
				sourceRows: src.rows,
				sourceHash: src.hash,
				targetRows: null,
				targetHash: null,
				ok: null,
			});
		}
	} else {
		// ONE transaction for the whole load and every setval, so a failure anywhere leaves the target
		// exactly as it was. There is no half-loaded state to reason about afterwards.
		await pg.query("BEGIN");
		try {
			if (options.truncate && targetTables.length > 0) {
				await pg.query(
					`TRUNCATE TABLE ${targetTables.map(quoteIdent).join(", ")} RESTART IDENTITY CASCADE`,
				);
				truncated = true;
			}
			const loaded: { table: TablePlan; rows: number; hash: string }[] = [];
			for (const table of plan.tables) {
				const src = await loadTable({ db, pg, plan: table, coercions, write: true });
				loaded.push({ table, rows: src.rows, hash: src.hash });
			}
			for (const { table } of loaded) sequences.push(...(await resetSequences(pg, table)));
			await pg.query("COMMIT");
			for (const entry of loaded) {
				results.push({
					table: entry.table.table,
					sourceRows: entry.rows,
					sourceHash: entry.hash,
					targetRows: null,
					targetHash: null,
					ok: null,
				});
			}
		} catch (err) {
			await pg.query("ROLLBACK").catch(() => {});
			throw err;
		}
		// Verification runs AFTER the commit, against committed data, so what it reports is what a later
		// reader would see rather than what this transaction could see about itself.
		for (const result of results) {
			const table = plan.tables.find((t) => t.table === result.table)!;
			const dst = await hashTarget(pg, table);
			result.targetRows = dst.rows;
			result.targetHash = dst.hash;
			result.ok = result.sourceRows === dst.rows && result.sourceHash === dst.hash;
		}
		sequences = await readSequences(pg, sequences);
	}

	const failures: string[] = [];
	for (const result of results) {
		if (result.ok === false) {
			failures.push(
				`${result.table}: ${result.sourceRows} rows / ${result.sourceHash.slice(0, 16)} in the source, ${result.targetRows} rows / ${(result.targetHash ?? "").slice(0, 16)} in the target`,
			);
		}
	}
	for (const sequence of sequences) {
		if (!sequence.ok) {
			failures.push(
				`${sequence.table}.${sequence.column}: the sequence will hand out ${sequence.nextValue} and the table already holds id ${sequence.maxId}. The first insert after the cutover would collide.`,
			);
		}
	}
	if (results.length === 0) {
		failures.push("no table was processed at all, which is a failure however cleanly it exited.");
	}

	return {
		mode: options.verifyOnly ? "verify-only" : options.dryRun ? "dry-run" : "load",
		source: options.sourcePath,
		startedAt,
		finishedAt: now().toISOString(),
		tables: results,
		sequences,
		coercions: coercions.all(),
		expectedSkips: plan.expectedSkips,
		unexpectedSkips: plan.unexpectedSkips,
		targetOnlyTables: plan.targetOnlyTables,
		targetOnlyColumns: plan.tables
			.filter((t) => t.targetOnlyColumns.length > 0)
			.map((t) => ({ table: t.table, columns: t.targetOnlyColumns })),
		truncated,
		ok: failures.length === 0,
		failures,
	};
}

// --- the report -------------------------------------------------------------------------------------

function pad(text: string, width: number): string {
	return text.length >= width ? text : text + " ".repeat(width - text.length);
}

function padStart(text: string, width: number): string {
	return text.length >= width ? text : " ".repeat(width - text.length) + text;
}

/**
 * THE ARTIFACT. rows and hash for both sides, per table, on one line each -- the thing the cutover is
 * judged on. Printed whether the run passed or failed, because a report you only get when it worked is
 * not evidence.
 */
export function renderReport(report: ExportReport): string {
	const lines: string[] = [];
	lines.push(`ob 323 SQLite -> Postgres export  [${report.mode}]`);
	lines.push(`source: ${report.source}`);
	lines.push(`started: ${report.startedAt}  finished: ${report.finishedAt}`);
	if (report.truncated) lines.push("target: TRUNCATED before loading (--truncate)");
	lines.push("");

	const nameWidth = Math.max(24, ...report.tables.map((t) => t.table.length));
	lines.push(
		`${pad("table", nameWidth)}  ${padStart("rows(src)", 9)}  ${padStart("rows(dst)", 9)}  ${pad("hash(src)", 16)}  ${pad("hash(dst)", 16)}  status`,
	);
	for (const table of report.tables) {
		const status = table.ok === null ? "scanned" : table.ok ? "OK" : "MISMATCH";
		lines.push(
			`${pad(table.table, nameWidth)}  ${padStart(String(table.sourceRows), 9)}  ${padStart(
				table.targetRows === null ? "-" : String(table.targetRows),
				9,
			)}  ${pad(table.sourceHash.slice(0, 16), 16)}  ${pad(
				table.targetHash === null ? "-" : table.targetHash.slice(0, 16),
				16,
			)}  ${status}`,
		);
	}
	const totalRows = report.tables.reduce((sum, t) => sum + t.sourceRows, 0);
	lines.push("");
	lines.push(`${report.tables.length} tables, ${totalRows} source rows`);

	if (report.sequences.length > 0) {
		lines.push("");
		lines.push("identity sequences (ob 321: inserted ids kept, so each sequence is re-set)");
		const seqWidth = Math.max(20, ...report.sequences.map((s) => `${s.table}.${s.column}`.length));
		for (const sequence of report.sequences) {
			lines.push(
				`  ${pad(`${sequence.table}.${sequence.column}`, seqWidth)}  max id ${padStart(
					sequence.maxId === null ? "-" : String(sequence.maxId),
					9,
				)}  next ${padStart(String(sequence.nextValue), 9)}  ${sequence.ok ? "OK" : "WOULD COLLIDE"}`,
			);
		}
	}

	if (report.coercions.length > 0) {
		lines.push("");
		lines.push("values whose SQLite storage type did not match the target column (coerced, not dropped)");
		for (const coercion of report.coercions) {
			lines.push(
				`  ${coercion.table}.${coercion.column}: ${coercion.count} value(s) stored as ${coercion.from} [${coercion.samples.join(", ")}]`,
			);
		}
	}
	if (report.targetOnlyColumns.length > 0) {
		lines.push("");
		lines.push("target-only columns, left to their defaults (ob 322's search columns land here)");
		for (const entry of report.targetOnlyColumns) lines.push(`  ${entry.table}: ${entry.columns.join(", ")}`);
	}
	if (report.expectedSkips.length > 0) {
		lines.push("");
		lines.push(`source tables not moved, by design (fts5 + sqlite bookkeeping): ${report.expectedSkips.length}`);
		lines.push(`  ${report.expectedSkips.join(", ")}`);
	}
	if (report.unexpectedSkips.length > 0) {
		lines.push("");
		lines.push(`source tables NOT MOVED and not part of the seam: ${report.unexpectedSkips.join(", ")}`);
	}
	if (report.targetOnlyTables.length > 0) {
		lines.push("");
		lines.push(`target tables with no source, left empty: ${report.targetOnlyTables.join(", ")}`);
	}

	lines.push("");
	if (report.ok) {
		lines.push(
			report.mode === "dry-run"
				? "DRY RUN OK: every row read and coerced without a refusal. Nothing was written."
				: "VERIFIED: every table matches on both row count and content hash, and every sequence clears its max id.",
		);
	} else {
		lines.push("FAILED:");
		for (const failure of report.failures) lines.push(`  ${failure}`);
	}
	return lines.join("\n");
}
